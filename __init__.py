#
# WHERE THE LETTER ACTUALLY GOES
# ------------------------------
# In Edit Mode on a text object, bpy.ops.font.text_insert() puts the character at the text cursor,
# which is what a person editing text expects. Outside Edit Mode there is no cursor to speak of, so
# the letter is appended to the object's body instead and the button says so. With no text object
# at all the panel explains rather than silently doing nothing.

import json
import os

import bpy
from bpy.props import EnumProperty, StringProperty
from bpy.types import Operator, Panel

from . import accents

HERE = os.path.dirname(os.path.abspath(__file__))
MAX_SHOWN = 60          # a panel redraws every mouse move; 682 buttons would crawl
COLUMNS = 10

_letters_cache = None


def letters():
    """The 682 letters, read once per session.

    Generated by extension/build.mjs from Unicode 16.0.0 and CLDR 48.2.0 — the same data as the
    Accent Letters website and every other add-on, so a letter cannot differ between them.
    """
    global _letters_cache
    if _letters_cache is None:
        with open(os.path.join(HERE, 'letters.json'), encoding='utf-8') as handle:
            _letters_cache = json.load(handle)['letters']
    return _letters_cache


def search(query):
    """Match over the prebuilt haystack each row carries.

    That 't' field holds the letter, its Unicode name, its accent mark, the languages that use it,
    its code point and its Alt code — so "two dots", "spanish", "00e9" and "é" all find é without
    this file knowing anything about any of them.
    """
    needle = (query or '').strip().lower()
    rows = letters()
    if needle:
        rows = [row for row in rows if needle in row['t']]
    return rows[:MAX_SHOWN]


def active_text(context):
    """The active object if it is a text object, else None."""
    obj = context.active_object
    return obj if obj is not None and obj.type == 'FONT' else None


class ACCENTLETTERS_OT_insert(Operator):
    bl_idname = 'accent_letters.insert'
    bl_label = 'Insert accented letter'
    bl_description = 'Put this letter in the active text object'
    bl_options = {'REGISTER', 'UNDO'}

    character: StringProperty(name='Character', default='')

    def execute(self, context):
        if not self.character:
            self.report({'WARNING'}, 'No letter given')
            return {'CANCELLED'}

        obj = active_text(context)
        if obj is None:
            self.report({'WARNING'}, 'Select a text object first')
            return {'CANCELLED'}

        if context.mode == 'EDIT_TEXT':
            # The only path that respects where the caret is. Everything else appends.
            bpy.ops.font.text_insert(text=self.character)
            self.report({'INFO'}, 'Inserted %s' % self.character)
        else:
            obj.data.body += self.character
            self.report({'INFO'}, 'Added %s to the end of the text' % self.character)
        return {'FINISHED'}


class ACCENTLETTERS_OT_remove(Operator):
    bl_idname = 'accent_letters.remove_accents'
    bl_label = 'Remove accents'
    bl_description = 'Rewrite the selected text objects without their accents'
    bl_options = {'REGISTER', 'UNDO'}

    convert_special: EnumProperty(
        name='Letters with no plain form',
        description='What to do with ø, ł, đ, ß, æ, œ and þ, which Unicode does not decompose',
        items=[
            ('CONVERT', 'Convert', 'ø becomes o, ß becomes ss, æ becomes ae'),
            ('KEEP', 'Keep', 'Leave them as they are'),
        ],
        default='CONVERT',
    )
    german: EnumProperty(
        name='German umlauts',
        items=[
            ('DROP', 'Drop the mark', 'ä becomes a'),
            ('SPELL', 'Spell out', 'ä becomes ae'),
        ],
        default='DROP',
    )

    @classmethod
    def poll(cls, context):
        return any(o.type == 'FONT' for o in context.selected_objects)

    def execute(self, context):
        special = self.convert_special == 'CONVERT'
        german = self.german == 'SPELL'

        # Read every object's text before changing any of it, so a failure part way through cannot
        # leave some objects converted and others not.
        edits = []
        for obj in context.selected_objects:
            if obj.type != 'FONT':
                continue
            before = obj.data.body
            after = accents.remove_accents(before, special=special, german=german)
            if after != before:
                edits.append((obj, after))

        if not edits:
            # Rewriting with an identical copy still costs an undo step, for no change.
            self.report({'INFO'}, 'There are no accents to remove in the selected text')
            return {'CANCELLED'}

        for obj, after in edits:
            obj.data.body = after

        self.report({'INFO'}, 'Removed accents in %d text object%s'
                    % (len(edits), '' if len(edits) == 1 else 's'))
        return {'FINISHED'}


class ACCENTLETTERS_PT_panel(Panel):
    bl_idname = 'ACCENTLETTERS_PT_panel'
    bl_label = 'Accent Letters'
    bl_space_type = 'VIEW_3D'
    bl_region_type = 'UI'
    bl_category = 'Accent Letters'

    def draw(self, context):
        layout = self.layout
        scene = context.scene

        layout.prop(scene, 'accent_letters_search', text='', icon='VIEWZOOM')

        obj = active_text(context)
        if obj is None:
            layout.label(text='Select a text object', icon='INFO')
        elif context.mode == 'EDIT_TEXT':
            layout.label(text='Goes in at the cursor', icon='OUTLINER_DATA_FONT')
        else:
            layout.label(text='Adds to the end — Tab to edit', icon='OUTLINER_DATA_FONT')

        rows = search(scene.accent_letters_search)
        if not rows:
            layout.label(text='No letter matches that', icon='INFO')
        else:
            grid = layout.grid_flow(row_major=True, columns=COLUMNS, even_columns=True, align=True)
            for row in rows:
                grid.operator('accent_letters.insert', text=row['c']).character = row['c']
            if len(rows) == MAX_SHOWN:
                layout.label(text='Showing the first %d — keep typing to narrow' % MAX_SHOWN)

        layout.separator()
        layout.operator('accent_letters.remove_accents', icon='SORTALPHA')


CLASSES = (ACCENTLETTERS_OT_insert, ACCENTLETTERS_OT_remove, ACCENTLETTERS_PT_panel)


def register():
    for cls in CLASSES:
        bpy.utils.register_class(cls)
    # On the Scene rather than the add-on preferences: it is a transient filter, and putting it in
    # preferences would persist a half-typed search across sessions.
    bpy.types.Scene.accent_letters_search = StringProperty(
        name='Search',
        description='Search by the letter, its name, the accent mark, a language or a code point',
        default='',
        options={'TEXTEDIT_UPDATE'},
    )


def unregister():
    del bpy.types.Scene.accent_letters_search
    for cls in reversed(CLASSES):
        bpy.utils.unregister_class(cls)
